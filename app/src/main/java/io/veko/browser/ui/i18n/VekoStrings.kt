        return when (language.resolveLanguageCode(systemLocale)) {
            "vi" -> vi
            "ja" -> ja
            "ko" -> ko
            "zh-CN" -> zhCn
            "fr" -> fr
            "de" -> de
            "es" -> es
            else -> en
        }
    }

