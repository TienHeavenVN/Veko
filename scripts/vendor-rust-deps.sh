#!/usr/bin/env bash
# Quản lý vendoring ngoại tuyến & kiểm định toàn vẹn SHA-256 cho crate Rust veko-adblock-ffi (F-Droid compatible):
#   --prepare         : Chạy `cargo vendor --locked --versioned-dirs`, tạo `.cargo/config.toml`
#                       và đối chiếu SHA-256 `.cargo-checksum.json` với `Cargo.lock`.
#   --verify-offline  : Kiểm định `Cargo.lock` + `.cargo-checksum.json` và chạy `cargo test --release --locked --offline`
#                       với `CARGO_NET_OFFLINE=true` (tuyệt đối không kết nối Internet).
#   --clean           : Xóa thư mục tạm `vendor/` và `.cargo/config.toml`.
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "${SCRIPT_DIR}/.." && pwd)"
CRATE_DIR="${REPO_ROOT}/privacy/rust/veko-adblock"
LOCKFILE="${CRATE_DIR}/Cargo.lock"
VENDOR_DIR="${CRATE_DIR}/vendor"
CARGO_CFG_DIR="${CRATE_DIR}/.cargo"
CARGO_CFG_FILE="${CARGO_CFG_DIR}/config.toml"

ACTION=""
for arg in "$@"; do
  case "${arg}" in
    --prepare|--verify-offline|--clean)
      ACTION="${arg}"
      ;;
    *)
      echo "[ERROR] Unknown argument: ${arg} (expected --prepare | --verify-offline | --clean)" >&2
      exit 1
      ;;
  esac
done

if [[ -z "${ACTION}" ]]; then
  echo "[ERROR] Missing mode flag (--prepare | --verify-offline | --clean)" >&2
  exit 1
fi

verify_vendor_checksums() {
  python3 - "${LOCKFILE}" "${VENDOR_DIR}" <<'PY'
import hashlib, json, pathlib, sys, tomllib

lock_path = pathlib.Path(sys.argv[1])
vendor_dir = pathlib.Path(sys.argv[2])

if not lock_path.is_file():
    raise SystemExit(f"[ERROR] Missing lockfile: {lock_path}")
if not vendor_dir.is_dir():
    raise SystemExit(f"[ERROR] Missing vendor directory: {vendor_dir}")

lock = tomllib.loads(lock_path.read_text(encoding="utf-8"))
packages = lock.get("package", [])
verified_crates = 0
verified_files = 0

for pkg in packages:
    name = pkg["name"]
    version = pkg["version"]
    source = pkg.get("source")
    expected_pkg_cksum = pkg.get("checksum")
    if source is None:
        continue
    if source != "registry+https://github.com/rust-lang/crates.io-index":
        raise SystemExit(f"[ERROR] Unexpected non-crates.io source for {name} {version}: {source}")
    if not expected_pkg_cksum or len(expected_pkg_cksum) != 64:
        raise SystemExit(f"[ERROR] Missing or invalid SHA-256 checksum in Cargo.lock for {name} {version}")

    crate_dir = vendor_dir / f"{name}-{version}"
    if not crate_dir.is_dir():
        crate_dir = vendor_dir / name
    cksum_file = crate_dir / ".cargo-checksum.json"
    if not cksum_file.is_file():
        raise SystemExit(f"[ERROR] Missing .cargo-checksum.json in {crate_dir}")

    meta = json.loads(cksum_file.read_text(encoding="utf-8"))
    actual_pkg_cksum = meta.get("package")
    if actual_pkg_cksum != expected_pkg_cksum:
        raise SystemExit(
            f"[ERROR] Package SHA-256 mismatch for {name} {version}: "
            f"Cargo.lock={expected_pkg_cksum} vs vendor={actual_pkg_cksum}"
        )

    files_map = meta.get("files", {})
    for rel_file, expected_file_sha in files_map.items():
        fp = crate_dir / rel_file
        if not fp.is_file():
            raise SystemExit(f"[ERROR] Missing vendored source file {fp}")
        digest = hashlib.sha256(fp.read_bytes()).hexdigest()
        if digest != expected_file_sha:
            raise SystemExit(
                f"[ERROR] File SHA-256 mismatch in {fp}: expected {expected_file_sha}, got {digest}"
            )
        verified_files += 1
    verified_crates += 1

print(
    f"[OK] Verified {verified_crates} vendored crates and {verified_files} unpacked source files "
    f"against {lock_path.name} SHA-256 checksums."
)
PY
}

case "${ACTION}" in
  --clean)
    rm -rf "${VENDOR_DIR}" "${CARGO_CFG_FILE}"
    rmdir "${CARGO_CFG_DIR}" 2>/dev/null || true
    echo "[OK] Cleaned vendored Rust artifacts in ${CRATE_DIR}."
    ;;

  --prepare)
    if [[ ! -f "${LOCKFILE}" ]]; then
      echo "[ERROR] ${LOCKFILE} does not exist. Commit a verified Cargo.lock first." >&2
      exit 1
    fi
    rm -rf "${VENDOR_DIR}"
    mkdir -p "${CARGO_CFG_DIR}"
    (
      cd "${CRATE_DIR}"
      cargo vendor --locked --versioned-dirs vendor >/dev/null
    )
    cat > "${CARGO_CFG_FILE}" <<'EOF'
# Generated by scripts/vendor-rust-deps.sh for deterministic offline / F-Droid builds.
[source.crates-io]
replace-with = "vendored-sources"

[source.vendored-sources]
directory = "vendor"
EOF
    verify_vendor_checksums
    ;;

  --verify-offline)
    if [[ ! -f "${CARGO_CFG_FILE}" || ! -d "${VENDOR_DIR}" ]]; then
      echo "[ERROR] Vendored directory or .cargo/config.toml missing. Run '--prepare' during prebuild/fetch first." >&2
      exit 1
    fi
    verify_vendor_checksums
    (
      cd "${CRATE_DIR}"
      export CARGO_NET_OFFLINE=true
      cargo metadata --format-version 1 --locked --offline > "${VENDOR_DIR}/cargo-metadata.json"
      python3 - "${VENDOR_DIR}/cargo-metadata.json" <<'PY'
import json, pathlib, sys
meta = json.loads(pathlib.Path(sys.argv[1]).read_text(encoding="utf-8"))
ALLOWED_TOKENS = {"MPL-2.0", "MIT", "Apache-2.0", "Unicode-3.0", "Unlicense", "BSD-2-Clause", "BSD-3-Clause", "ISC", "Zlib"}
for pkg in meta["packages"]:
    lic = (pkg.get("license") or "").strip()
    assert lic, f"[ERROR] Crate {pkg['name']} {pkg['version']} has no SPDX license field!"
    tokens = [t.strip("()") for t in lic.replace("/", " ").split() if t not in {"OR", "AND", "WITH"}]
    disallowed = [t for t in tokens if t not in ALLOWED_TOKENS]
    assert not disallowed, f"[ERROR] Disallowed SPDX token {disallowed} in {pkg['name']} {pkg['version']}: {lic}"
print(f"[OK] Verified SPDX open-source licenses across all {len(meta['packages'])} Cargo packages (offline).")
PY
      rm -f "${VENDOR_DIR}/cargo-metadata.json"
      cargo test --release --locked --offline
    )
    echo "[OK] Offline Rust build & unit test suite succeeded with CARGO_NET_OFFLINE=true (--locked --offline)."
    ;;
esac
