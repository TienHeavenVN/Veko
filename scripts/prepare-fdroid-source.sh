#!/usr/bin/env bash
# Chuẩn bị cây mã nguồn Veko cho F-Droid `prebuild:` và kiểm định `fdroid scanner`:
#   1. Khóa cứng `settings.gradle.kts` sang chế độ `mavenLocal()` thuần nguồn cục bộ và loại bỏ hoàn toàn
#      URL `https://maven.mozilla.org/maven2/` (tránh lỗi tĩnh `Found unknown maven repo` của `fdroid scanner`
#      và ngăn tuyệt đối mọi khả năng fallback tải AAR dựng sẵn từ Mozilla Maven).
#   2. Nếu thư mục `privacy/rust/veko-adblock/vendor/` đã được tạo bởi `vendor-rust-deps.sh --prepare`
#      (sau khi đã xác thực SHA-256 nguyên bản đối chiếu `Cargo.lock`), dọn các tệp nhị phân mẫu thử nghiệm
#      (`tests/`, `benches/`, `fuzz/`, `testdata/`) bị `fdroid scanner` cảnh báo và đồng bộ lại bảng `"files"`
#      trong `.cargo-checksum.json` (giữ nguyên khóa `"package"`) để `cargo --locked --offline` hoạt động 100%.
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "${SCRIPT_DIR}/.." && pwd)"

for arg in "$@"; do
  case "${arg}" in
    --repo-root=*)
      REPO_ROOT="$(cd "${arg#*=}" && pwd)"
      ;;
    --help|-h)
      echo "Usage: bash scripts/prepare-fdroid-source.sh [--repo-root=/path/to/Veko]"
      exit 0
      ;;
    *)
      echo "[ERROR] Unknown argument: ${arg}" >&2
      exit 1
      ;;
  esac
done

SETTINGS_FILE="${REPO_ROOT}/settings.gradle.kts"
VENDOR_DIR="${REPO_ROOT}/privacy/rust/veko-adblock/vendor"

if [[ ! -f "${SETTINGS_FILE}" ]]; then
  echo "[BUILD_SCRIPT_ERROR] Missing settings.gradle.kts at ${SETTINGS_FILE}" >&2
  exit 1
fi

cat > "${SETTINGS_FILE}" <<'EOF'
pluginManagement {
    repositories {
        google()
        mavenCentral()
        gradlePluginPortal()
    }
}

// Generated by scripts/prepare-fdroid-source.sh for F-Droid offline source builds:
// GeckoView MUST resolve exclusively from local source-built mavenLocal() artifacts (MozFennec).
val useMavenLocalGecko = true

dependencyResolutionManagement {
    repositoriesMode.set(RepositoriesMode.FAIL_ON_PROJECT_REPOS)
    repositories {
        google()
        mavenCentral()
        if (useMavenLocalGecko) {
            mavenLocal {
                content {
                    includeGroup("org.mozilla.geckoview")
                }
            }
        }
    }
}

rootProject.name = "Veko"

include(
    ":app",
    ":browser-core",
    ":privacy",
    ":downloads",
    ":storage",
    ":security",
    ":testing",
)
EOF

# Kiểm tra fail-closed: không còn bất kỳ khai báo kho Mozilla Maven nào trong các tệp cấu hình Gradle
python3 - "${REPO_ROOT}" <<'PY'
import pathlib, sys

root = pathlib.Path(sys.argv[1])
gradle_files = [root / "settings.gradle.kts", root / "build.gradle.kts"] + sorted(root.glob("*/build.gradle.kts"))
for gf in gradle_files:
    if not gf.is_file():
        continue
    text = gf.read_text(encoding="utf-8")
    if "https://maven.mozilla.org" in text or "http://maven.mozilla.org" in text:
        raise SystemExit(f"[BUILD_SCRIPT_ERROR] Forbidden Mozilla Maven URL still present in {gf}")
print(f"[OK] Stripped Mozilla Maven repository from settings.gradle.kts and verified {len(gradle_files)} Gradle files.")
PY

if [[ -d "${VENDOR_DIR}" ]]; then
  python3 - "${VENDOR_DIR}" <<'PY'
import json, pathlib, re, sys

vendor_dir = pathlib.Path(sys.argv[1])
# Khớp chính xác tập phần mở rộng & quy tắc nhị phân của fdroidserver/scanner.py (scan_source)
SCANNER_ARCHIVE_OR_BIN_EXTS = {
    ".a", ".aar", ".apk", ".bin", ".class", ".dex", ".dll", ".dylib",
    ".exe", ".gz", ".jar", ".lib", ".out", ".so", ".tgz", ".wasm", ".zip",
}
VERSIONED_SO_RE = re.compile(r".*\.so(\..+)+$")
NON_BUILD_DIRS = {"tests", "test", "benches", "bench", "fuzz", "testdata", "fixtures", "examples", "ci", "docs"}
TEXT_CHARS = bytearray({7, 8, 9, 10, 12, 13, 27} | set(range(0x20, 0x100)) - {0x7F})

def is_binary_sample(path: pathlib.Path) -> bool:
    with path.open("rb") as fh:
        sample = fh.read(1024)
    return bool(sample.translate(None, TEXT_CHARS))

removed_count = 0
updated_crates = 0

for crate_dir in sorted(p for p in vendor_dir.iterdir() if p.is_dir()):
    cksum_path = crate_dir / ".cargo-checksum.json"
    if not cksum_path.is_file():
        continue
    meta = json.loads(cksum_path.read_text(encoding="utf-8"))
    files_map = meta.get("files", {})
    crate_modified = False

    rs_sources_blob = "\n".join(
        rs.read_text(encoding="utf-8", errors="ignore")
        for rs in crate_dir.rglob("*.rs")
        if not any(part.lower() in NON_BUILD_DIRS for part in rs.relative_to(crate_dir).parts[:-1])
    )

    for file_path in sorted(p for p in crate_dir.rglob("*") if p.is_file()):
        rel_parts = file_path.relative_to(crate_dir).parts
        rel_posix = file_path.relative_to(crate_dir).as_posix()
        if rel_posix == ".cargo-checksum.json":
            continue
        in_non_build_dir = any(part.lower() in NON_BUILD_DIRS for part in rel_parts[:-1])
        suffix = file_path.suffix.lower()
        name = file_path.name

        is_scanner_flagged = (
            suffix in SCANNER_ARCHIVE_OR_BIN_EXTS
            or bool(VERSIONED_SO_RE.match(name))
            or (suffix == "" and is_binary_sample(file_path))
        )
        if not is_scanner_flagged:
            continue

        referenced_in_rust = name in rs_sources_blob
        if in_non_build_dir or not referenced_in_rust:
            file_path.unlink()
            files_map.pop(rel_posix, None)
            removed_count += 1
            crate_modified = True

    if crate_modified:
        meta["files"] = files_map
        cksum_path.write_text(json.dumps(meta, separators=(",", ":")), encoding="utf-8")
        updated_crates += 1

print(
    f"[OK] Sanitized vendored Rust crates for fdroid scanner: pruned {removed_count} non-source binary fixture(s) "
    f"across {updated_crates} crate(s) while preserving Cargo.lock package checksums."
)
PY
fi
