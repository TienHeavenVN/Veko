import kotlinx.coroutines.withContext
import java.util.Locale

enum class SuggestionSource {
    BOOKMARK,
    HISTORY,
}

@Immutable
data class AddressSuggestion(
    val title: String,
    val url: String,
    val source: SuggestionSource,
)

data class PortableBookmarkEntry(
    val url: String,
    val title: String,
    val createdAtEpochMs: Long = System.currentTimeMillis(),
)

/**
 * Bộ mã hóa / giải mã Dấu trang ngoại tuyến (hỗ trợ cả chuẩn Netscape HTML tiêu chuẩn trình duyệt
 * lẫn định dạng JSON gọn nhẹ), lọc nghiêm ngặt các scheme độc hại (`javascript:`, `data:`, `file:`).
 */
object BookmarkPortabilityCodec {

    private val netscapeAnchorRegex = Regex(
        pattern = """<a\b[^>]*\bhref\s*=\s*["']([^"']+)["'][^>]*>(.*?)</a>""",
        options = setOf(RegexOption.IGNORE_CASE, RegexOption.DOT_MATCHES_ALL),
    )

    private val jsonObjectRegex = Regex(
        pattern = """\{[^{}]*\}""",
        options = setOf(RegexOption.DOT_MATCHES_ALL),
    )

    fun encodeNetscapeHtml(items: List<BookmarkEntity>): String = buildString {
        appendLine("<!DOCTYPE NETSCAPE-Bookmark-file-1>")
        appendLine("<!-- Automatically generated by Veko Browser (Offline Export) -->")
        appendLine("<META HTTP-EQUIV=\"Content-Type\" CONTENT=\"text/html; charset=UTF-8\">")
        appendLine("<TITLE>Veko Bookmarks</TITLE>")
        appendLine("<H1>Veko Bookmarks</H1>")
        appendLine("<DL><p>")
        for (item in items) {
            val safeUrl = UrlNavigationPolicy.stripUserInfo(item.url)
            if (!UrlNavigationPolicy.isRecordableHttpUrl(safeUrl)) continue
            val epochSec = (item.createdAtEpochMs / 1000L).coerceAtLeast(0L)
            val safeTitle = escapeHtml(item.title.ifBlank { safeUrl })
            appendLine("    <DT><A HREF=\"${escapeHtml(safeUrl)}\" ADD_DATE=\"$epochSec\">$safeTitle</A>")
        }
        appendLine("</DL><p>")
    }

    fun encodeJson(items: List<BookmarkEntity>): String = buildString {
        appendLine("{")
        appendLine("  \"format\": \"veko-bookmarks-v1\",")
        appendLine("  \"bookmarks\": [")
        val valid = items.filter { UrlNavigationPolicy.isRecordableHttpUrl(UrlNavigationPolicy.stripUserInfo(it.url)) }
        valid.forEachIndexed { index, item ->
            val safeUrl = UrlNavigationPolicy.stripUserInfo(item.url)
            val safeTitle = item.title.ifBlank { safeUrl }
            val comma = if (index < valid.lastIndex) "," else ""
            appendLine(
                "    {\"url\": \"${escapeJson(safeUrl)}\", \"title\": \"${escapeJson(safeTitle)}\", \"createdAtEpochMs\": ${item.createdAtEpochMs}}$comma",
            )
        }
        appendLine("  ]")
        append("}")
    }

    fun decodeBookmarks(rawContent: String): List<PortableBookmarkEntry> {
        val trimmed = rawContent.trim()
        if (trimmed.isEmpty()) return emptyList()
        val parsed = if (trimmed.startsWith("{") || trimmed.startsWith("[")) {
            parseJsonBookmarks(trimmed)
        } else {
            parseNetscapeHtmlBookmarks(trimmed)
        }
        val deduplicated = LinkedHashMap<String, PortableBookmarkEntry>()
        for (entry in parsed) {
            val cleanUrl = UrlNavigationPolicy.stripUserInfo(entry.url.trim())
            if (!UrlNavigationPolicy.isRecordableHttpUrl(cleanUrl)) continue
            val cleanTitle = entry.title.trim().ifBlank { UrlNavigationPolicy.formatDisplayHost(cleanUrl) }
            deduplicated.putIfAbsent(
                cleanUrl,
                PortableBookmarkEntry(
                    url = cleanUrl,
                    title = cleanTitle.take(256),
                    createdAtEpochMs = entry.createdAtEpochMs,
                ),
            )
        }
        return deduplicated.values.toList()
    }

    private fun parseNetscapeHtmlBookmarks(html: String): List<PortableBookmarkEntry> {
        return netscapeAnchorRegex.findAll(html).mapNotNull { match ->
            val rawHref = unescapeHtml(match.groupValues[1]).trim()
            val rawTitle = unescapeHtml(match.groupValues[2].replace(Regex("<[^>]+>"), "")).trim()
            if (rawHref.isEmpty()) null else PortableBookmarkEntry(url = rawHref, title = rawTitle)
        }.toList()
    }

    private fun parseJsonBookmarks(json: String): List<PortableBookmarkEntry> {
        return jsonObjectRegex.findAll(json).mapNotNull { objMatch ->
            val block = objMatch.value
            val url = extractJsonStringField(block, "url") ?: return@mapNotNull null
            val title = extractJsonStringField(block, "title").orEmpty()
            val ts = Regex(""""createdAtEpochMs"\s*:\s*(\d+)""")
                .find(block)
                ?.groupValues
                ?.getOrNull(1)
                ?.toLongOrNull()
                ?: System.currentTimeMillis()
            PortableBookmarkEntry(url = url, title = title, createdAtEpochMs = ts)
        }.toList()
    }

    private fun extractJsonStringField(objBlock: String, key: String): String? {
        val regex = Regex(""""${Regex.escape(key)}"\s*:\s*"((?:\\.|[^"\\])*)"""")
        val raw = regex.find(objBlock)?.groupValues?.getOrNull(1) ?: return null
        return unescapeJson(raw)
    }

    private fun escapeHtml(input: String): String = buildString(input.length) {
        for (ch in input) {
            when (ch) {
                '&' -> append("&amp;")
                '<' -> append("&lt;")
                '>' -> append("&gt;")
                '"' -> append("&quot;")
                '\'' -> append("&#39;")
                else -> append(ch)
            }
        }
    }

    private fun unescapeHtml(input: String): String = input
        .replace("&quot;", "\"")
        .replace("&#39;", "'")
        .replace("&lt;", "<")
        .replace("&gt;", ">")
        .replace("&amp;", "&")

    private fun escapeJson(input: String): String = buildString(input.length) {
        for (ch in input) {
            when (ch) {
                '\\' -> append("\\\\")
                '"' -> append("\\\"")
                '\n' -> append("\\n")
                '\r' -> append("\\r")
                '\t' -> append("\\t")
                else -> append(ch)
            }
        }
    }

    private fun unescapeJson(input: String): String = buildString(input.length) {
        var i = 0
        while (i < input.length) {
            val ch = input[i]
            if (ch == '\\' && i + 1 < input.length) {
                when (val next = input[i + 1]) {
                    '\\' -> { append('\\'); i += 2 }
                    '"' -> { append('"'); i += 2 }
                    '/' -> { append('/'); i += 2 }
                    'n' -> { append('\n'); i += 2 }
                    'r' -> { append('\r'); i += 2 }
                    't' -> { append('\t'); i += 2 }
                    'u' -> {
                        if (i + 5 < input.length) {
                            val hex = input.substring(i + 2, i + 6)
                            val code = hex.toIntOrNull(16)
                            if (code != null) {
                                append(code.toChar())
                                i += 6
                            } else {
                                append(next)
                                i += 2
                            }
                        } else {
                            append(next)
                            i += 2
                        }
                    }
                    else -> { append(next); i += 2 }
                }
            } else {
                append(ch)
                i += 1
            }
        }
    }
}

/**
 * Kho dữ liệu tập trung cho Lịch sử & Dấu trang, chạy hoàn toàn ngoài UI Thread.
 */
class BrowserDataRepository(
    private val historyDao: HistoryDao,
    private val bookmarkDao: BookmarkDao,
    private val ioDispatcher: CoroutineDispatcher = Dispatchers.IO,
) {
    val recentHistory: Flow<List<HistoryEntity>> = historyDao.observeRecentHistory()
    val bookmarks: Flow<List<BookmarkEntity>> = bookmarkDao.observeAllBookmarks()

    fun observeIsBookmarked(url: String): Flow<Boolean> = bookmarkDao.observeIsBookmarked(url)

    suspend fun recordVisitIfRegular(url: String, title: String, isPrivate: Boolean) {
        // Rào chắn kép: chỉ ghi lịch sử cho tab thường với URL http/https hợp lệ, chặn tuyệt đối tab riêng tư và URI nội bộ
        if (isPrivate || !UrlNavigationPolicy.isRecordableHttpUrl(url)) return
        withContext(ioDispatcher) {
            historyDao.insert(
                HistoryEntity(
                    url = url.trim(),
                    title = title.trim().ifBlank { url.trim() },
                ),
            )
        }
    }

    suspend fun toggleBookmark(url: String, title: String): Boolean {
        if (!UrlNavigationPolicy.isRecordableHttpUrl(url)) return false
        return withContext(ioDispatcher) {
            val normalized = url.trim()
            val existing = bookmarkDao.findByUrl(normalized)
            if (existing != null) {
                bookmarkDao.deleteByUrl(normalized)
                false
            } else {
                bookmarkDao.upsert(
                    BookmarkEntity(
                        url = normalized,
                        title = title.trim().ifBlank { normalized },
                    ),
                )
                true
            }
        }
    }

    suspend fun deleteBookmark(url: String) = withContext(ioDispatcher) {
        bookmarkDao.deleteByUrl(url)
    }

    suspend fun exportBookmarksHtml(): String = withContext(ioDispatcher) {
        val current = runCatching { bookmarkDao.observeAllBookmarks().first() }.getOrDefault(emptyList())
        BookmarkPortabilityCodec.encodeNetscapeHtml(current)
    }

    suspend fun exportBookmarksJson(): String = withContext(ioDispatcher) {
        val current = runCatching { bookmarkDao.observeAllBookmarks().first() }.getOrDefault(emptyList())
        BookmarkPortabilityCodec.encodeJson(current)
    }

    suspend fun importBookmarks(rawContent: String): Int = withContext(ioDispatcher) {
        val decoded = BookmarkPortabilityCodec.decodeBookmarks(rawContent)
        var importedCount = 0
        for (entry in decoded) {
            val existing = bookmarkDao.findByUrl(entry.url)
            bookmarkDao.upsert(
                BookmarkEntity(
                    id = existing?.id ?: 0L,
                    url = entry.url,
                    title = entry.title,
                    createdAtEpochMs = existing?.createdAtEpochMs ?: entry.createdAtEpochMs,
                ),
            )
            importedCount += 1
        }
        importedCount
    }

    /**
     * Lưu hoặc cập nhật lối tắt trang web trực tiếp vào bảng Room bookmarks hiện hữu (không sinh kho lưu trữ trùng lặp).
     * Chấp nhận cả URL đầy đủ (https://...) lẫn tên miền gọn (mozilla.org) và từ chối chuỗi tìm kiếm/scheme không an toàn.
     */
    suspend fun saveShortcutBookmark(rawUrlOrDomain: String, customTitle: String?): Boolean {
        val trimmedInput = rawUrlOrDomain.trim()
        if (trimmedInput.isEmpty() || trimmedInput.any(Char::isWhitespace)) return false
        val normalized = UrlNavigationPolicy.normalizeUserInput(trimmedInput, SearchEngine.DUCKDUCKGO)
        if (!UrlNavigationPolicy.isRecordableHttpUrl(normalized)) return false
        if (normalized.startsWith("${SearchEngine.DUCKDUCKGO.homeUrl}/?q=")) return false

        val cleanUrl = UrlNavigationPolicy.stripUserInfo(normalized)
        if (!UrlNavigationPolicy.isRecordableHttpUrl(cleanUrl)) return false
        val resolvedTitle = customTitle?.trim()?.takeIf(String::isNotBlank)
            ?: UrlNavigationPolicy.formatDisplayHost(cleanUrl)

        return withContext(ioDispatcher) {
            val existing = bookmarkDao.findByUrl(cleanUrl)
            bookmarkDao.upsert(
                BookmarkEntity(
                    id = existing?.id ?: 0L,
                    url = cleanUrl,
                    title = resolvedTitle,
                    createdAtEpochMs = existing?.createdAtEpochMs ?: System.currentTimeMillis(),
                ),
            )
            true
        }
    }

    suspend fun deleteHistoryItem(id: Long) = withContext(ioDispatcher) {
        historyDao.deleteById(id)
    }

    suspend fun clearAllHistory() = withContext(ioDispatcher) {
        historyDao.clearAll()
    }

    suspend fun searchHistory(rawQuery: String, limit: Int = 100): List<HistoryEntity> {
        val needle = rawQuery.trim()
        if (needle.isEmpty()) return emptyList()
        return withContext(ioDispatcher) {
            historyDao.searchHistory(needle, limit)
        }
    }

    /**
     * Gợi ý nhanh từ Dấu trang và Lịch sử đã lưu khi người dùng gõ trên thanh địa chỉ (không ghi bất kỳ dữ liệu nào).
     */
    suspend fun searchSuggestions(rawQuery: String, limit: Int = 6): List<AddressSuggestion> {
        val needle = rawQuery.trim()
        if (needle.isEmpty() || needle.length > 256) return emptyList()
        return withContext(ioDispatcher) {
            val lowerNeedle = needle.lowercase(Locale.ROOT)
            val seenUrls = LinkedHashSet<String>()
            val combined = ArrayList<AddressSuggestion>(limit)

            val allBookmarks = runCatching { bookmarkDao.observeAllBookmarks().first() }.getOrDefault(emptyList())
            for (bm in allBookmarks) {
                if (combined.size >= limit) break
                val matches = bm.url.lowercase(Locale.ROOT).contains(lowerNeedle) ||
                    bm.title.lowercase(Locale.ROOT).contains(lowerNeedle)
                if (matches && seenUrls.add(bm.url)) {
                    combined.add(
                        AddressSuggestion(
                            title = bm.title.ifBlank { bm.url },
                            url = bm.url,
                            source = SuggestionSource.BOOKMARK,
                        ),
                    )
                }
            }

            if (combined.size < limit) {
                val historyMatches = runCatching { historyDao.searchHistory(needle, limit * 2) }.getOrDefault(emptyList())
                for (entry in historyMatches) {
                    if (combined.size >= limit) break
                    if (seenUrls.add(entry.url)) {
                        combined.add(
                            AddressSuggestion(
                                title = entry.title.ifBlank { entry.url },
                                url = entry.url,
                                source = SuggestionSource.HISTORY,
                            ),
                        )
                    }
                }
            }
            combined
        }
    }
}
